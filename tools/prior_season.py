"""Generate `src/fpl_cli/domain/season_prior.py` from a pinned previous season.

model-1.4.md §2 and §4. Reads the vaastav archive's `fixtures.csv` and
`teams.csv` for 2025-26, pinned in `~/fpl-pinned/` by sha256, fits them with the
same machinery component/1.3 uses (`fit_results`), and writes the result as a
committed module so the CLI never touches the network and tests never read
`~/fpl-pinned`.

Clubs are keyed by FPL `code`, which persists across seasons; `id` does not.
Relegated clubs are the 2025-26 codes absent from a 2026-27 bootstrap, and the
promoted clubs' prior is their mean — fitted, not chosen.

Lives in `tools/`, not `src/fpl_cli`, so nothing shipped can import it.

Usage: python tools/prior_season.py [--pinned ~/fpl-pinned] [--check]
`--check` regenerates in memory and fails if the committed module differs.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import statistics
import sys
from pathlib import Path

from fpl_cli.api.models import Fixture
from fpl_cli.domain.strength import fit_results

PINNED = Path.home() / "fpl-pinned"
SEASON = "2025-26"
FIXTURES = f"{SEASON}-fixtures.csv"
TEAMS = f"{SEASON}-teams.csv"
# The 2026-27 club list. Any pinned 2026-27 bootstrap will do — the league's
# membership does not change within a season.
CURRENT = "gw5-pre-deadline.json"
EXPECTED_SHA256 = {
    FIXTURES: "2d7e3950d346df14ca486cb09e9b9ba406d37d943775244eed06cdc021ffb3a9",
    TEAMS: "b29df099cb0ad25413e284e53116099b0e0496874f99743dbc0870d8241b46c5",
}
TARGET = Path(__file__).resolve().parent.parent / "src" / "fpl_cli" / "domain" / "season_prior.py"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def render(pinned: Path) -> str:
    for name, expected in EXPECTED_SHA256.items():
        actual = sha256(pinned / name)
        if actual != expected:
            raise SystemExit(f"{name}: sha256 {actual} is not the pinned {expected} (model-1.4.md §2).")

    code_by_id = {int(row["id"]): int(row["code"]) for row in csv.DictReader((pinned / TEAMS).open())}
    results = [
        Fixture(
            id=int(row["id"]),
            event=int(row["event"]),
            team_h=int(row["team_h"]),
            team_a=int(row["team_a"]),
            team_h_score=int(row["team_h_score"]),
            team_a_score=int(row["team_a_score"]),
            finished=True,
        )
        for row in csv.DictReader((pinned / FIXTURES).open())
        if row["finished"] == "True" and row["team_h_score"] not in ("", "None")
    ]
    if len(results) != 380:
        raise SystemExit(f"{SEASON} has {len(results)} finished results, not 380 — not a complete season.")

    fit = fit_results(results, sorted(code_by_id))
    if fit.fallback is not None:
        raise SystemExit(f"{SEASON} fit fell back ({fit.fallback}); a complete season should not.")
    ratings = {code_by_id[team]: (fit.attack[team], fit.defence[team]) for team in code_by_id}

    current_codes = {team["code"] for team in json.loads((pinned / CURRENT).read_text())["teams"]}
    relegated = sorted(code for code in ratings if code not in current_codes)
    if len(relegated) != 3:
        raise SystemExit(f"Expected three relegated clubs, found {len(relegated)}: {relegated}.")
    promoted_prior = (
        statistics.fmean(ratings[code][0] for code in relegated),
        statistics.fmean(ratings[code][1] for code in relegated),
    )

    rows = "\n".join(f"    {code}: ({attack!r}, {defence!r})," for code, (attack, defence) in sorted(ratings.items()))
    return f'''"""GENERATED by tools/prior_season.py from the pinned {SEASON} season. Do not edit.

model-1.4.md §2: the previous season's venue factors and per-club (attack,
defence) ratings, keyed by FPL club `code`. Promoted clubs — any current club
whose code is not below — take `PROMOTED_PRIOR`, the relegated clubs' mean.

Sources (sha256):
  {FIXTURES}  {EXPECTED_SHA256[FIXTURES]}
  {TEAMS}  {EXPECTED_SHA256[TEAMS]}
  {CURRENT} (2026-27 membership)  {sha256(pinned / CURRENT)}

Every value is covered by the component/1.4 variants' digests; regenerating
with different inputs makes them different models.
"""

SEASON = "{SEASON}"
MU = {fit.mu!r}
HOME_FACTOR = {fit.home_factor!r}
AWAY_FACTOR = {fit.away_factor!r}
RATINGS: dict[int, tuple[float, float]] = {{
{rows}
}}
RELEGATED: tuple[int, ...] = {tuple(relegated)!r}
PROMOTED_PRIOR: tuple[float, float] = {promoted_prior!r}
'''


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--pinned", default=str(PINNED))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render(Path(args.pinned).expanduser())
    if args.check:
        same = TARGET.exists() and TARGET.read_text() == text
        print("season_prior.py matches its inputs." if same else "season_prior.py DIFFERS from its inputs.")
        return 0 if same else 1
    TARGET.write_text(text)
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
